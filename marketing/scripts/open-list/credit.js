/**
 * A recipe's credit in the open list. The standard is the Credit section of
 * the recipe's own page (src/pages/gallery/[slug].astro): the same facts and
 * the same links, so an entry never credits less than its page.
 * parity.test.js builds the real pages and holds the two together.
 *
 * Ported, not imported: the page writes its credit inline, and its licence
 * links are in src/lib/gallery-api.ts, which Node cannot load (it reaches
 * astro:content). Follow-up: one plain-JS credit module that both use.
 */
import { code, link, text } from './markdown.js';

/** @typedef {import('../../src/lib/gallery-schema.js').Recipe} Recipe */
/** @typedef {'en' | 'zh'} Lang */

/**
 * The canonical page of each licence a source list may carry: LICENCE_URLS in
 * src/lib/gallery-api.ts. open-list.test.js holds the keys to the schema's
 * LICENCES, and parity.test.js the links to the ones the pages show.
 * @type {Readonly<Record<Recipe['source']['licence'], string>>}
 */
export const LICENCE_URLS = Object.freeze({
  'CC0-1.0': 'https://creativecommons.org/publicdomain/zero/1.0/',
  'CC-BY-4.0': 'https://creativecommons.org/licenses/by/4.0/',
  MIT: 'https://opensource.org/license/mit',
  'Apache-2.0': 'https://www.apache.org/licenses/LICENSE-2.0',
});

/**
 * Where the source list can be read, as the recipe page links it: a list
 * named "owner/repo" is a GitHub repository, opened at the commit it was read
 * at when that is a commit hash. Any other name has no link.
 *
 * @param {{ list: string, list_commit: string }} source
 * @returns {string | null}
 */
export function listUrlOf(source) {
  if (!/^[\w.-]+\/[\w.-]+$/.test(source.list)) return null;
  const atCommit = /^[0-9a-f]{7,40}$/.test(source.list_commit) ? `/tree/${source.list_commit}` : '';
  return `https://github.com/${source.list}${atCommit}`;
}

/**
 * The credit as data, for data/recipes.json.
 * @param {Recipe} recipe
 */
export function creditOf(recipe) {
  const { source } = recipe;
  return {
    author: source.author,
    author_url: source.author_url,
    original_url: source.original_url,
    list: source.list,
    list_commit: source.list_commit,
    list_url: listUrlOf(source),
    licence: source.licence,
    licence_url: LICENCE_URLS[source.licence],
    changes: [...source.changes],
  };
}

/**
 * What the import tool's change notes mean, in Chinese. The note itself is
 * always shown as it was recorded; these only explain the ones the tool
 * writes (scripts/gallery/stages/translate.js).
 * @type {Readonly<Record<string, string>>}
 */
const CHANGES_ZH = Object.freeze({
  'translated to Chinese': '译为中文',
  'translated to English': '译为英文',
  'title translated to English': '标题译为英文',
  'placeholders resolved': '占位符已填入默认值',
  'placeholders rewritten as {{name}}': '占位符改写为 {{name}} 形式',
});

/**
 * The credit in Markdown, as three sentences in one paragraph: who wrote the
 * prompt, where they posted it, the list it came from and its licence; what
 * was changed from the original; and that Godance generated the output from
 * it, and the sample inputs too when the recipe has them.
 *
 * @param {Recipe} recipe
 * @param {Lang} lang
 */
export function creditMarkdown(recipe, lang) {
  const credit = creditOf(recipe);
  const author = link(text(credit.author), credit.author_url);
  const list = credit.list_url ? link(code(credit.list), credit.list_url) : code(credit.list);
  const licence = link(text(credit.licence), credit.licence_url);
  const video = recipe.modality === 'VIDEO';
  const samples = recipe.inputs?.length ?? 0;

  if (lang === 'zh') {
    const post = link('原帖', credit.original_url);
    const changes = credit.changes.length > 0
      ? `与原作相比的改动：${credit.changes.map((change) => (CHANGES_ZH[change] ? `${text(change)}（${CHANGES_ZH[change]}）` : text(change))).join('；')}。`
      : '提示词按原样使用，未作改动。';
    const output = `${video ? '视频' : '图片'}由 Godance 根据该提示词生成${samples > 0 ? '，示例输入图也由 Godance 生成，不来自任何清单或照片' : ''}。`;
    return `提示词作者：${author}（${post}），来自清单 ${list}，许可协议：${licence}。${changes}${output}`;
  }

  const post = link('original post', credit.original_url);
  const changes = credit.changes.length > 0
    ? `Changes from the original: ${credit.changes.map(text).join('; ')}.`
    : 'The prompt is used as published, unchanged.';
  const inputs = samples === 0 ? ''
    : samples === 1 ? ', and so was the sample input: it comes from no list and no photo'
    : ', and so were the sample inputs: they come from no list and no photo';
  const output = `The ${video ? 'video' : 'image'} was generated by Godance from that prompt${inputs}.`;
  return `Prompt by ${author} (${post}), from the list ${list}, licensed ${licence}. ${changes} ${output}`;
}
